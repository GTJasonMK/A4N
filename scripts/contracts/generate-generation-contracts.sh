#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib/common.sh
source "$SCRIPT_DIR/../lib/common.sh"
FRONTEND="$PROJECT_ROOT/frontend"
SCHEMA="$FRONTEND/src/api/generated/generation-contract.schema.json"
TYPES="$FRONTEND/src/api/generated/generationContracts.ts"
BANNER='// @generated by `scripts/contracts/generate-generation-contracts.sh`.'

write_types() {
    (cd "$FRONTEND" && npx --no-install json2ts \
        -i "src/api/generated/generation-contract.schema.json" \
        -o "src/api/generated/generationContracts.ts" \
        --bannerComment "$BANNER")
}

case "${1:---check}" in
    --write)
        cargo run -q --manifest-path "$PROJECT_ROOT/Cargo.toml" \
            -p a4n-api-contract --bin export_generation_schema -- --write
        write_types
        ;;
    --check)
        tmp_dir="$(make_target_temp_dir generation-contracts)"
        trap 'rm -rf "$tmp_dir"' EXIT
        cargo run -q --manifest-path "$PROJECT_ROOT/Cargo.toml" \
            -p a4n-api-contract --bin export_generation_schema > "$tmp_dir/schema.json"
        (cd "$FRONTEND" && npx --no-install json2ts \
            -i "$tmp_dir/schema.json" \
            -o "$tmp_dir/generationContracts.ts" \
            --bannerComment "$BANNER")
        cmp -s "$tmp_dir/schema.json" "$SCHEMA" || {
            printf 'generation schema is stale; run --write\n' >&2
            exit 1
        }
        cmp -s "$tmp_dir/generationContracts.ts" "$TYPES" || {
            printf 'generated TypeScript is stale; run --write\n' >&2
            exit 1
        }
        ;;
    *)
        printf 'usage: %s [--write|--check]\n' "$0" >&2
        exit 2
        ;;
esac

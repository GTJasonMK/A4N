import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(path.join(root, "frontend/package.json"));
const Ajv2020 = require("ajv/dist/2020").default;
const standaloneCode = require("ajv/dist/standalone").default;
const ucs2length = require("ajv/dist/runtime/ucs2length").default;

// Use AJV's own closure-free Unicode helper in the generated ESM. Its default
// standalone reference uses CommonJS require, which browsers cannot execute.
ucs2length.code = `(${ucs2length.toString()})`;

export const validatorTypes = {
  eventValidator: "GenerationTaskEvent",
  snapshotValidator: "GenerationTaskSnapshot",
  handleValidator: "GenerationTaskHandle",
  subscriptionHandleValidator: "GenerationSubscriptionHandle",
  summaryValidator: "GenerationTaskSummary",
  historyValidator: "GenerationTaskHistoryPage",
  hostErrorValidator: "HostErrorResponse",
};

export function compileGenerationValidators(schema) {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true, lines: true },
    formats: { float: true, int32: true, int64: true, uint16: true, uint32: true, uint64: true },
  });
  const schemaId = "a4n-generation-contract";
  ajv.addSchema(schema, schemaId);
  const refs = Object.fromEntries(Object.entries(validatorTypes).map(([name, type]) => [name, `${schemaId}#/$defs/${type}`]));
  const validators = Object.fromEntries(Object.entries(refs).map(([name, ref]) => {
    const validate = ajv.getSchema(ref);
    if (!validate) throw new Error(`${ref} schema is missing`);
    return [name, validate];
  }));
  return { ajv, refs, validators };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 4) throw new Error("usage: generate-generation-validators.mjs schema.json output-directory");
  const schema = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
  const output = process.argv[3];
  const { ajv, refs } = compileGenerationValidators(schema);
  const banner = "// @generated by `scripts/contracts/generate-generation-contracts.sh`.\n";
  const types = `${banner}import type { ErrorObject } from "ajv";
import type * as Contract from "./generationContracts";

type Validator<T> = {
  (value: unknown): value is T;
  errors?: ErrorObject[] | null;
};

${Object.entries(validatorTypes).map(([name, type]) => `export const ${name}: Validator<Contract.${type}>;`).join("\n")}
`;
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, "generationValidators.js"), banner + standaloneCode(ajv, refs));
  fs.writeFileSync(path.join(output, "generationValidators.d.ts"), types);
}

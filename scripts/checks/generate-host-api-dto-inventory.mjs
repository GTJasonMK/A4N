#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const runtimeRoot = path.join(root, "crates", "a4n-runtime", "src", "actions");
const outputPath = path.join(
  root,
  "scripts",
  "checks",
  "host-api-dto-inventory.tsv",
);
const hostApiSource = fs.readFileSync(
  path.join(root, "crates", "a4n-runtime", "src", "host_api.rs"),
  "utf8",
);
const consumers = {
  server: sourceFiles(path.join(root, "crates", "a4n-server", "src"), ".rs"),
  tauri: sourceFiles(path.join(root, "crates", "a4n-tauri", "src"), ".rs"),
  frontend: sourceFiles(path.join(root, "frontend", "src", "api"), ".ts"),
};

const declarations = [];
for (const file of sourceFiles(runtimeRoot, ".rs")) {
  const source = fs.readFileSync(file, "utf8");
  const relative = path.relative(root, file).replaceAll(path.sep, "/");
  const actionModule = actionModuleFor(relative);
  const pattern = /^pub\s+(struct|enum|type)\s+([A-Za-z_][A-Za-z0-9_]*)/gm;
  for (const match of source.matchAll(pattern)) {
    const [declaration, kind, name] = match;
    const lineStart = match.index ?? 0;
    const prefix = source.slice(Math.max(0, lineStart - 500), lineStart);
    const declarationEnd = kind === "type" ? source.indexOf(";", lineStart) + 1 : source.indexOf("\n", lineStart);
    const declarationSource = source.slice(lineStart, declarationEnd > lineStart ? declarationEnd : undefined);
    declarations.push({
      actionModule,
      declaration,
      file: relative,
      frontend: references(consumers.frontend, name),
      kind,
      name,
      prefix,
      publicModule: new RegExp(`\\b${escapeRegex(actionModule)}\\b`).test(hostApiSource),
      server: references(consumers.server, name),
      tauri: references(consumers.tauri, name),
      target: kind === "type" ? declarationSource.split("=").slice(1).join("=").trim() : "",
    });
  }
}

const declarationsByName = new Map();
for (const item of declarations) {
  const values = declarationsByName.get(item.name) ?? [];
  values.push(item);
  declarationsByName.set(item.name, values);
}
const duplicateNames = new Set(
  [...declarationsByName]
    .filter(([, values]) => values.length > 1)
    .map(([name]) => name),
);

const rows = declarations
  .map((item) => {
    const frontendDefinition = item.frontend.some(({ source }) =>
      new RegExp(`export\\s+(?:interface|type|enum)\\s+${escapeRegex(item.name)}\\b`).test(source),
    );
    return [
      item.file,
      item.kind,
      item.name,
      classification(item, duplicateNames),
      item.publicModule ? "yes" : "no",
      serdeWire(item.prefix),
      frontendDefinition ? "yes" : "no",
      consumerPaths(item.server),
      consumerPaths(item.tauri),
      consumerPaths(item.frontend),
    ].join("\t");
  })
  .sort();

const output = [
  "# Generated by scripts/checks/generate-host-api-dto-inventory.mjs; do not edit manually.",
  "file\tkind\ttype\tclassification\tpublic_host_module\tserde_wire\tfrontend_schema_duplicate\tserver_consumers\ttauri_consumers\tfrontend_consumers",
  ...rows,
  "",
].join("\n");

switch (process.argv[2]) {
  case "--write":
    fs.writeFileSync(outputPath, output);
    break;
  case "--check": {
    const existing = fs.readFileSync(outputPath, "utf8");
    if (existing !== output) {
      throw new Error("Host API DTO inventory is stale; run with --write");
    }
    break;
  }
  default:
    process.stdout.write(output);
}

function actionModuleFor(relative) {
  const actionPath = relative.split("/src/actions/")[1];
  return actionPath.split("/")[0].replace(/\.rs$/, "");
}

function classification(item, duplicateNames) {
  if (duplicateNames.has(item.name)) return "duplicate";
  if (/(?:ProgressReporter|TaskScope|Runtime)$/.test(item.name) || item.name === "CharacterAiProgress") {
    return "runtime_internal";
  }
  if (/a4n_(?:service_protocol|capabilities)/.test(item.target)) return "sidecar_contract";
  if (/a4n_(?:core|db|domain|orchestrator|image|video|llm|rag_core)/.test(item.target)) {
    return "domain_value";
  }
  if (item.publicModule && (item.server.length || item.tauri.length || item.frontend.length)) {
    return "public_host_contract";
  }
  return "runtime_internal";
}

function serdeWire(prefix) {
  const flags = [];
  if (/\bSerialize\b/.test(prefix)) flags.push("serialize");
  if (/\bDeserialize\b/.test(prefix)) flags.push("deserialize");
  if (/deny_unknown_fields/.test(prefix)) flags.push("deny_unknown_fields");
  if (/serde\s*\([^)]*default/.test(prefix)) flags.push("default");
  const rename = prefix.match(/rename_all\s*=\s*"([^"]+)"/);
  if (rename) flags.push(`rename_all=${rename[1]}`);
  return flags.join(",") || "none";
}

function references(files, symbol) {
  const pattern = new RegExp(`\\b${escapeRegex(symbol)}\\b`);
  return files
    .map((file) => ({ file, source: fs.readFileSync(file, "utf8") }))
    .filter(({ source }) => pattern.test(source));
}

function consumerPaths(items) {
  return items
    .map(({ file }) => path.relative(root, file).replaceAll(path.sep, "/"))
    .sort()
    .join(",");
}

function sourceFiles(directory, extension) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const current = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...sourceFiles(current, extension));
    else if (entry.isFile() && entry.name.endsWith(extension)) files.push(current);
  }
  return files.sort();
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

fn test_segment_performance_plan(
    duration_secs: i32,
    movement_path: &str,
    visible_action: &str,
    gaze: &str,
    camera_relationship: &str,
) -> Value {
    json!({
        "movement_path": movement_path,
        "body_performance": "肩膀收紧，重心随动作缓慢移动，结束时稳定停住。",
        "gaze_and_hands": format!("视线{gaze}，双手保持与当前动作一致的可见状态。"),
        "pause_or_reaction": "动作完成后停半拍，让紧张反应和结尾状态清楚可见。",
        "camera_relationship": camera_relationship,
        "time_blocks": [{
            "start_sec": 0,
            "end_sec": duration_secs,
            "camera": camera_relationship,
            "subject_action": visible_action,
            "continuity_target": "保持人物身份、服装、空间锚点和光源方向连续。"
        }],
        "action_script": [{
            "character": "小宦官",
            "body": "肩膀收紧，重心缓慢移动后稳定停住。",
            "movement": visible_action,
            "hands": "双手保持与当前动作一致的可见状态，不凭空新增道具。",
            "gaze": gaze,
            "timing": "全段"
        }]
    })
}

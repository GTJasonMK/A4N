//! In-memory contracts shared by video providers and their Host adapters.
//!
//! Wire request payloads stay in `a4n-video-sidecar-contract`; provider
//! implementations and routing rules stay in `a4n-video`.

use serde_json::Value;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProviderImageInputTransport {
    PublicUrl,
    InlineDataUrl,
    RemoteTempUpload,
}

#[derive(Debug, Clone)]
pub struct VideoGenerationResult {
    pub bytes: Vec<u8>,
    pub format: String,
    pub provider_job_id: Option<String>,
    pub metadata: Value,
}

#[derive(Debug, Clone)]
pub enum VideoJobState {
    Pending,
    Running,
    Completed(VideoGenerationResult),
    Failed(String),
}

/// Provider state without the generated bytes. Cleanup/reconcile must use this
/// contract so a status check cannot accidentally download a completed video.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VideoJobStatus {
    Pending,
    Running,
    Completed,
    Failed(String),
    Cancelled,
    NotFound,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VideoJobDeleteOutcome {
    Deleted,
    NotFound,
}

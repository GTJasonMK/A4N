use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use serde_json::Value;

use a4n_core::error::AppError;

pub const OPENAI_COMPATIBLE_VIDEO_BACKEND: &str = "openai-compatible-video";
pub const NEWAPI_VIDEO_BACKEND: &str = "newapi-video";
pub const GEMINI_VEO_VIDEO_BACKEND: &str = "gemini-veo-video";
pub const SEEDANCE2_VIDEO_BACKEND: &str = "seedance2-video";
pub const CLIPROXY_OPENAI_VIDEO_BACKEND: &str = "cliproxy-openai-video";
pub const OPENAI_CHAT_VIDEO_BACKEND: &str = "openai-chat-video";

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
pub enum VideoMediaInput {
    None,
    Frames {
        first: String,
        last: Option<String>,
        references: Vec<String>,
    },
    References {
        images: Vec<String>,
        videos: Vec<String>,
        audio: Vec<String>,
    },
}

impl VideoMediaInput {
    pub fn from_images(
        first: Option<String>,
        last: Option<String>,
        references: Vec<String>,
    ) -> Result<Self, AppError> {
        match (first, last, references) {
            (Some(first), last, references) => Ok(Self::Frames {
                first,
                last,
                references,
            }),
            (None, Some(_), _) => Err(AppError::InvalidArgument(
                "视频尾帧不能脱离首帧单独存在".to_string(),
            )),
            (None, None, images) if !images.is_empty() => Ok(Self::References {
                images,
                videos: Vec::new(),
                audio: Vec::new(),
            }),
            (None, None, _) => Ok(Self::None),
        }
    }

    pub fn first_frame(&self) -> Option<&str> {
        match self {
            Self::Frames { first, .. } => Some(first),
            _ => None,
        }
    }

    pub fn last_frame(&self) -> Option<&str> {
        match self {
            Self::Frames { last, .. } => last.as_deref(),
            _ => None,
        }
    }

    pub fn reference_images(&self) -> &[String] {
        match self {
            Self::Frames { references, .. } => references,
            Self::References { images, .. } => images,
            Self::None => &[],
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct VideoGenerationRequest {
    pub prompt: String,
    pub negative_prompt: Option<String>,
    pub width: i32,
    pub height: i32,
    pub duration_secs: i32,
    pub fps: i32,
    pub model: String,
    pub media: VideoMediaInput,
}

impl VideoGenerationRequest {
    pub fn validate_dimensions(&self) -> Result<(), AppError> {
        if self.width <= 0 || self.height <= 0 {
            return Err(AppError::InvalidArgument(
                "视频请求宽度和高度必须为正整数".to_string(),
            ));
        }
        Ok(())
    }
}

#[derive(Debug, Clone)]
pub struct VideoGenerationResult {
    pub bytes: Vec<u8>,
    pub format: String,
    pub provider_job_id: Option<String>,
    pub metadata: Value,
}

#[derive(Debug, Clone)]
pub enum VideoJobState {
    Pending,
    Running,
    Completed(VideoGenerationResult),
    Failed(String),
}

/// Provider state without the generated bytes. Cleanup/reconcile must use this
/// contract so a status check cannot accidentally download a completed video.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum VideoJobStatus {
    Pending,
    Running,
    Completed,
    Failed(String),
    Cancelled,
    NotFound,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VideoJobDeleteOutcome {
    Deleted,
    NotFound,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VideoCancelConfirmation {
    NotApplicable,
    RequiresReconcile,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VideoPollingProfile {
    pub interval_secs: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct VideoProviderCleanupCapabilities {
    pub asynchronous: bool,
    pub cancel: bool,
    pub status_query: bool,
    pub delete: bool,
    pub cancel_confirmation: VideoCancelConfirmation,
    pub polling_profile: Option<VideoPollingProfile>,
}

const ASYNC_VIDEO_CLEANUP_CAPABILITIES: VideoProviderCleanupCapabilities =
    VideoProviderCleanupCapabilities {
        asynchronous: true,
        cancel: false,
        status_query: true,
        delete: false,
        cancel_confirmation: VideoCancelConfirmation::RequiresReconcile,
        polling_profile: Some(VideoPollingProfile { interval_secs: 60 }),
    };

const OPENAI_VIDEO_CLEANUP_CAPABILITIES: VideoProviderCleanupCapabilities =
    VideoProviderCleanupCapabilities {
        delete: true,
        ..ASYNC_VIDEO_CLEANUP_CAPABILITIES
    };

const SYNC_VIDEO_CLEANUP_CAPABILITIES: VideoProviderCleanupCapabilities =
    VideoProviderCleanupCapabilities {
        asynchronous: false,
        cancel: false,
        status_query: false,
        delete: false,
        cancel_confirmation: VideoCancelConfirmation::NotApplicable,
        polling_profile: None,
    };

/// The single backend/capability registry used by config validation, sidecars,
/// and cleanup. Unknown backends intentionally return `None`.
pub fn video_provider_cleanup_capabilities(
    backend: &str,
) -> Option<VideoProviderCleanupCapabilities> {
    match backend {
        OPENAI_COMPATIBLE_VIDEO_BACKEND
        | NEWAPI_VIDEO_BACKEND
        | GEMINI_VEO_VIDEO_BACKEND
        | SEEDANCE2_VIDEO_BACKEND => Some(ASYNC_VIDEO_CLEANUP_CAPABILITIES),
        CLIPROXY_OPENAI_VIDEO_BACKEND => Some(OPENAI_VIDEO_CLEANUP_CAPABILITIES),
        OPENAI_CHAT_VIDEO_BACKEND => Some(SYNC_VIDEO_CLEANUP_CAPABILITIES),
        _ => None,
    }
}

#[async_trait]
pub trait VideoProvider: Send + Sync {
    async fn generate(
        &self,
        req: VideoGenerationRequest,
        provider_idempotency_key_sha256: Option<&str>,
    ) -> Result<VideoGenerationResult, AppError>;

    async fn poll(&self, job_id: &str) -> Result<VideoJobState, AppError>;

    /// Query only remote state. Implementations must not download a completed
    /// artifact from this method.
    async fn status(&self, job_id: &str) -> Result<VideoJobStatus, AppError>;

    async fn delete(&self, _job_id: &str) -> Result<VideoJobDeleteOutcome, AppError> {
        Err(AppError::InvalidArgument(
            "视频 provider 不支持删除远端任务".to_string(),
        ))
    }
}

pub fn validate_video_provider_idempotency_key(value: Option<&str>) -> Result<(), AppError> {
    let Some(value) = value else {
        return Ok(());
    };
    if value.len() != 64
        || !value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
    {
        return Err(AppError::InvalidArgument(
            "视频 provider idempotency key 必须是小写 SHA-256".to_string(),
        ));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_covers_all_supported_backends_once() {
        for backend in [
            OPENAI_COMPATIBLE_VIDEO_BACKEND,
            NEWAPI_VIDEO_BACKEND,
            GEMINI_VEO_VIDEO_BACKEND,
            SEEDANCE2_VIDEO_BACKEND,
        ] {
            let capabilities = video_provider_cleanup_capabilities(backend).unwrap();
            assert!(capabilities.asynchronous);
            assert!(capabilities.status_query);
            assert!(!capabilities.cancel);
            assert!(!capabilities.delete);
            assert_eq!(
                capabilities.cancel_confirmation,
                VideoCancelConfirmation::RequiresReconcile
            );
        }
        let openai = video_provider_cleanup_capabilities(CLIPROXY_OPENAI_VIDEO_BACKEND).unwrap();
        assert!(openai.asynchronous);
        assert!(openai.status_query);
        assert!(!openai.cancel);
        assert!(openai.delete);
        let chat = video_provider_cleanup_capabilities(OPENAI_CHAT_VIDEO_BACKEND).unwrap();
        assert!(!chat.asynchronous);
        assert!(!chat.status_query);
        assert!(video_provider_cleanup_capabilities("unknown").is_none());
    }

    #[test]
    fn provider_idempotency_key_is_optional_lowercase_sha256() {
        assert!(validate_video_provider_idempotency_key(None).is_ok());
        assert!(validate_video_provider_idempotency_key(Some(&"a".repeat(64))).is_ok());
        assert!(validate_video_provider_idempotency_key(Some(&"A".repeat(64))).is_err());
        assert!(validate_video_provider_idempotency_key(Some("short")).is_err());
    }

    #[test]
    fn request_dimensions_must_be_positive() {
        let request = VideoGenerationRequest {
            prompt: "test".into(),
            negative_prompt: None,
            width: 0,
            height: 720,
            duration_secs: 5,
            fps: 24,
            model: "model".into(),
            media: VideoMediaInput::None,
        };
        assert!(request.validate_dimensions().is_err());
    }
}
